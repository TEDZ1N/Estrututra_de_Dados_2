from collections import deque

# ---------- 1. MODELO ----------
# Lista de adjacência: dict[aeroporto] -> lista de vizinhos.
# Escolhi dict de listas porque o grafo é esparso (poucas rotas por
# aeroporto): ocupa O(V+E) de memória e percorrer vizinhos é direto.
#
# CGH Congonhas | GRU Guarulhos | VCP Viracopos | BSB Brasília
# CNF Confins   | SSA Salvador  | REC Recife    | FOR Fortaleza
ARESTAS = [
    ("CGH", "GRU"), ("CGH", "VCP"), ("GRU", "VCP"), ("GRU", "BSB"), ("VCP", "BSB"),
    ("BSB", "CNF"), ("BSB", "SSA"), ("CNF", "SSA"),
    ("SSA", "REC"), ("SSA", "FOR"), ("REC", "FOR"),
]


class Grafo:
    def __init__(self, arestas):
        self.adj = {}
        self.bloqueadas = set()  # rotas indisponíveis (frozenset de 2 vértices)
        for a, b in arestas:
            self.adj.setdefault(a, []).append(b)
            self.adj.setdefault(b, []).append(a)

    # Em vez de apagar a aresta, marco como bloqueada: assim posso
    # bloquear e desbloquear sem reconstruir o grafo.
    def bloquear(self, a, b):
        self.bloqueadas.add(frozenset((a, b)))

    def desbloquear(self, a, b):
        self.bloqueadas.discard(frozenset((a, b)))

    def vizinhos(self, v):
        return [w for w in self.adj[v] if frozenset((v, w)) not in self.bloqueadas]

    # ---------- 2. BFS ----------
    # Fila (FIFO): explora por "camadas". Em grafo sem pesos, o primeiro
    # caminho que chega ao destino é o de MENOR número de rotas.
    def bfs(self, origem, destino):
        pai = {origem: None}
        fila = deque([origem])
        ordem = []
        while fila:
            v = fila.popleft()
            ordem.append(v)
            if v == destino:
                return self._caminho(pai, destino), ordem
            for w in self.vizinhos(v):
                if w not in pai:
                    pai[w] = v
                    fila.append(w)
        return None, ordem

    # ---------- 3. DFS ----------
    # Pilha (LIFO): vai fundo por um ramo antes de voltar. Acha UM caminho,
    # não necessariamente o mais curto. Versão iterativa (evita estourar
    # o limite de recursão do Python em grafos grandes).
    def dfs(self, origem, destino):
        pai = {origem: None}
        pilha = [origem]
        visitados = set()
        ordem = []
        while pilha:
            v = pilha.pop()
            if v in visitados:
                continue
            visitados.add(v)
            ordem.append(v)
            if v == destino:
                return self._caminho(pai, destino), ordem
            # reversed() para visitar vizinhos na ordem em que aparecem
            for w in reversed(self.vizinhos(v)):
                if w not in visitados:
                    pai.setdefault(w, v)
                    pilha.append(w)
        return None, ordem

    @staticmethod
    def _caminho(pai, destino):
        caminho = []
        v = destino
        while v is not None:
            caminho.append(v)
            v = pai[v]
        return caminho[::-1]


# ---------- 4. SIMULAÇÃO ----------
def txt(vertices):
    return " -> ".join(str(v) for v in vertices)


def mostrar(titulo, g, origem, destino):
    print(f"\n--- {titulo} ({origem} -> {destino}) ---")
    for nome, algoritmo in (("BFS", g.bfs), ("DFS", g.dfs)):
        caminho, ordem = algoritmo(origem, destino)
        if caminho:
            print(f"{nome}: {txt(caminho)}  [{len(caminho) - 1} rotas]")
        else:
            print(f"{nome}: nenhum caminho disponível")
        print(f"     ordem de visita: {', '.join(str(v) for v in ordem)}")


